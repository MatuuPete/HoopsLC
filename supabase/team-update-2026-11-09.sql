catalog as (
  select id, name, price, team,
    regexp_replace(regexp_replace(lower(name), '[[:space:]]+(jr[.]?|sr[.]?|ii|iii|iv)$', ''), '[^a-z]', '', 'g') as name_key
  from player_catalog
),
updated as (
  update player_catalog p
  set team = e.team, updated_at = now()
  from catalog c join espn e on e.name_key = c.name_key
  where p.id = c.id and p.team is distinct from e.team
  returning p.id
)
select
  case when e.name_key is null then 'not on ESPN: unchanged' else 'updated' end as result,
  c.name, c.price, c.team as old_team, e.team as new_team
from catalog c left join espn e on e.name_key = c.name_key
where e.name_key is null or c.team is distinct from e.team
order by result desc, c.price desc;
